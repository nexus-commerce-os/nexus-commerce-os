// Fails the build if the security headers are not where the deploy will find
// them, or if the policy has been quietly loosened.
//
// WHY A SCRIPT AND NOT A REVIEW
// `public/_headers` is a plain text file that nothing imports, nothing types
// and nothing renders. If `next build` ever stops copying it, or a path moves,
// or a header is deleted in an unrelated edit, the site keeps working perfectly
// and ships with no protection at all. That failure is completely silent — the
// only way to notice is to measure a deployed response, and by then it is live.
//
// It reads `out/_headers`, the file that is actually uploaded, rather than the
// source in `public/`. Those are the same bytes right up until the day they are
// not, and the whole point of this check is to catch that day.
//
// THE WORKER IS CHECKED SEPARATELY, AND THAT IS NOT DUPLICATION
// Cloudflare's documentation for Workers static assets says custom headers from
// `_headers` "are not applied to responses generated by your Worker code". So
// `_headers` covers the pages and cannot cover /api/waitlist, which is the one
// route that accepts input. Two mechanisms, two checks.
//
// WHAT THIS CANNOT DO
// It proves the rules are present and well-formed in the artifact that ships.
// It does NOT prove Cloudflare applies them — only a request against a running
// deployment proves that, and no such deployment exists to test against yet.
// Nothing here should be read as that stronger claim.

import { readFile } from 'node:fs/promises';

/** Required on every static response. Lower-cased for comparison. */
const PAGE_HEADERS = [
  'strict-transport-security',
  'content-security-policy',
  'x-content-type-options',
  'x-frame-options',
  'referrer-policy',
  'permissions-policy',
];

/**
 * Required on responses the Worker builds itself. HSTS and CSP are here too:
 * an API that returns JSON should still refuse to be framed or sniffed.
 */
const WORKER_HEADERS = [
  'x-content-type-options',
  'x-frame-options',
  'referrer-policy',
  'content-security-policy',
  'strict-transport-security',
];

/**
 * Substrings that would defeat the policy. `unsafe-inline` is NOT here: Next's
 * static export inlines critical CSS, so style-src legitimately needs it. It is
 * checked below for script-src specifically, where there is no such excuse.
 */
const FORBIDDEN_IN_CSP = ["'unsafe-eval'", 'data: script-src', 'script-src *'];

const failures = [];

// ---------------------------------------------------------------------------
// 1. The static pages.
// ---------------------------------------------------------------------------
let headersFile;
try {
  headersFile = await readFile(new URL('../out/_headers', import.meta.url), 'utf8');
} catch {
  console.error(
    'verify-headers: out/_headers is missing.\n' +
      '  It lives in public/_headers and `next build` copies public/ into out/.\n' +
      '  If the build ran, this means the file is no longer being copied — the\n' +
      '  site would deploy with no security headers and look completely fine.',
  );
  process.exit(1);
}

const lower = headersFile.toLowerCase();

if (!/^\/\*\s*$/m.test(headersFile)) {
  failures.push('out/_headers has no `/*` rule — the headers would apply to nothing');
}

for (const name of PAGE_HEADERS) {
  // A header line is `  Name: value`; a comment line starts with `#`.
  const re = new RegExp(`^\\s*${name}\\s*:\\s*\\S`, 'mi');
  if (!re.test(headersFile)) failures.push(`out/_headers does not set ${name}`);
}

const cspLine = headersFile.split(/\r?\n/).find((l) => /^\s*content-security-policy\s*:/i.test(l));
if (cspLine) {
  for (const bad of FORBIDDEN_IN_CSP) {
    if (cspLine.toLowerCase().includes(bad)) failures.push(`CSP contains ${bad}`);
  }
  if (/script-src[^;]*'unsafe-inline'/i.test(cspLine)) {
    failures.push("CSP allows 'unsafe-inline' in script-src");
  }
  if (!/frame-ancestors\s+'none'/i.test(cspLine)) {
    failures.push("CSP does not set frame-ancestors 'none'");
  }
}

if (!/max-age=\d{7,}/.test(lower)) {
  failures.push('HSTS max-age is missing or shorter than ~4 months');
}

// ---------------------------------------------------------------------------
// 2. The Worker's own responses.
// ---------------------------------------------------------------------------
const worker = await readFile(new URL('../worker/index.ts', import.meta.url), 'utf8');
const workerLower = worker.toLowerCase();

for (const name of WORKER_HEADERS) {
  if (!workerLower.includes(`'${name}'`)) {
    failures.push(`worker/index.ts does not set ${name} on its own responses`);
  }
}

/*
 * Every Response the Worker builds must go through the one helper that applies
 * the headers. A bare `new Response(` anywhere else is how a header gets set on
 * five paths and silently missed on the sixth.
 */
const bareResponses = worker
  .split(/\r?\n/)
  .map((line, i) => [i + 1, line])
  .filter(([, line]) => /new Response\(/.test(line) && !/SECURITY_HEADERS/.test(line));

/*
 * TWO places legitimately build a Response, and both must keep their headers.
 *
 *   json()       — the Worker's own JSON answers, carrying SECURITY_HEADERS.
 *   serveAsset() — an asset re-emitted with a per-response CSP nonce. It does
 *                  NOT use SECURITY_HEADERS and must not: those are the API's
 *                  (`default-src 'none'`) and would break every page. It
 *                  copies the asset's own headers instead, so `public/_headers`
 *                  stays the one place the page policy is written.
 *
 * Admitting a second path is only safe if that path is checked, so it is —
 * below, and more closely than the line-position rule ever checked json().
 */
const workerLines = worker.split(/\r?\n/);
const windowAfter = (pattern, span) => {
  const at = workerLines.findIndex((l) => pattern.test(l));
  return at === -1 ? null : [at + 1, at + 1 + span];
};
const allowedWindows = [
  windowAfter(/const json = /, 6),
  windowAfter(/async function serveAsset\(/, 80),
].filter(Boolean);

const stray = bareResponses.filter(
  ([n]) => !allowedWindows.some(([from, to]) => n >= from && n <= to),
);
for (const [n] of stray) {
  failures.push(
    `worker/index.ts:${n} builds a Response outside json() or serveAsset() — it would carry no security headers`,
  );
}

/*
 * The nonce path, asserted rather than trusted. Each of these is a way a
 * nonce could look present and be worthless.
 */
if (/async function serveAsset\(/.test(worker)) {
  const nonceChecks = [
    [/crypto\.getRandomValues\(/, 'the nonce must come from the platform CSPRNG, not Math.random'],
    [
      /new Headers\(asset\.headers\)/,
      "the asset's own headers must be carried over, or the page loses everything _headers set",
    ],
    [
      /headers\.set\('cache-control', 'no-store'\)/,
      'HTML carrying a nonce must not be stored by a shared cache — a reused nonce is not a nonce',
    ],
    [
      /getAttribute\('src'\) !== null\) return/,
      "a script with src is already covered by 'self' and must not also be given a nonce",
    ],
    [/EXECUTABLE_TYPES/, 'only executable script types should receive the grant'],
    [/script-src \$\{sources\.trim\(\)\} 'nonce-/, 'the nonce must be ADDED to script-src, not replace it'],
  ];
  for (const [pattern, why] of nonceChecks) {
    if (!pattern.test(worker)) failures.push(`nonce CSP: ${why}`);
  }
  // Comments stripped first: the file EXPLAINS why it does not use
  // 'unsafe-inline', and a check that cannot tell prose from code would fire
  // on the explanation and teach everyone to delete the explanation.
  const workerCode = worker.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
  if (/'unsafe-inline'/.test(workerCode)) {
    failures.push("worker/index.ts reintroduces 'unsafe-inline' — the nonce exists to avoid it");
  }
}

// ---------------------------------------------------------------------------
if (failures.length > 0) {
  console.error(`verify-headers: ${failures.length} problem(s):\n  · ` + failures.join('\n  · '));
  process.exit(1);
}

console.log(
  `verify-headers: OK — ${PAGE_HEADERS.length} header rules present in out/_headers, ` +
    `${WORKER_HEADERS.length} set on the Worker's own responses, CSP not weakened. ` +
    `(Presence in the artifact, not proof that Cloudflare applies them.)`,
);

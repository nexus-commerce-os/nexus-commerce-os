// Cloudflare Worker that serves honesttotal.com.
//
// It does two things and nothing else:
//   1. POST /api/waitlist  — validate an email server-side and persist it to KV
//   2. everything else     — hand off to the static assets built by `next build`
//
// WHY A WORKER RATHER THAN A PURE STATIC SITE
// The marketing page posts to /api/waitlist. Under `output: 'export'` Next has
// no server to answer that, so the route lives here instead. The client calls
// the same same-origin path it always did, so no browser code changed.
//
// WHY KV RATHER THAN THE SCAFFOLD'S STORE
// The P0.1 scaffold kept addresses in process memory, which is right for a
// scaffold and wrong in production: every isolate restart would silently drop
// them while the page still told the visitor "You're on the list." Telling
// someone they are on a list that does not exist is not a bug we are willing to
// ship on a site whose entire claim is honesty. That module had no other
// consumer once the Next route moved here, so it was removed rather than left
// as dead code; an ESP driver, if wanted later, implements WaitlistStore here.

import {
  EMAIL_RE,
  type AddResult,
  type WaitlistEntry,
  type WaitlistStore,
} from '../src/lib/waitlist-contract';
import { handleCatalogApi, handleCatalogPage } from './catalog';

export interface Env {
  ASSETS: Fetcher;
  WAITLIST: KVNamespace;
  /**
   * The published catalogue. Optional on purpose: a deploy without the
   * binding serves the same honest "nothing published" as one with an empty
   * database, rather than turning a configuration gap into an outage.
   */
  CATALOG?: D1Database;
}

/**
 * KV-backed driver — same `WaitlistStore` interface as every other driver
 * (ADR-0010: providers are adapter-wrapped, so swapping the store never
 * reaches the caller).
 *
 * Dedup is a read-then-write, and KV is eventually consistent, so two requests
 * racing on the same address can both be recorded. That is the right trade
 * here: a duplicate row is harmless and fixable downstream, whereas the
 * alternatives (a lock, or a strongly-consistent store) would cost real
 * latency to prevent a cosmetic problem.
 */
class KvWaitlistStore implements WaitlistStore {
  constructor(private readonly kv: KVNamespace) {}

  async add(entry: WaitlistEntry): Promise<AddResult> {
    const key = `email:${entry.email.toLowerCase()}`;
    if ((await this.kv.get(key)) !== null) return { status: 'duplicate' };
    await this.kv.put(key, JSON.stringify(entry));
    return { status: 'added' };
  }
}

/*
 * Per-IP throttle on the one route that writes.
 *
 * WHY THIS IS HERE AT ALL
 * Workers KV on the free plan allows 1,000 writes per day, and every signup is
 * a write. Until now nothing stood between a script and that quota: a thousand
 * POSTs with distinct addresses would exhaust the day's budget, and every real
 * visitor afterwards would get "Could not save right now" until midnight UTC.
 * The failure would at least be honest -- the 502 path below is careful about
 * that -- but it would still be a day of lost signups bought for the price of
 * a loop.
 *
 * WHAT THIS IS NOT
 * State lives in the isolate, so this is per-isolate, not global. A spread-out
 * attacker gets a multiple of MAX_PER_WINDOW, not MAX_PER_WINDOW. It is a
 * speed bump that makes naive abuse uneconomic; it is NOT the real control.
 * The real control is a Cloudflare rate-limiting rule on /api/waitlist, which
 * the free plan includes one of. This exists because it is free, verifiable
 * without a deploy, and cannot break anything if the dashboard rule is never
 * added.
 *
 * The IP is personal data, so it is held in memory for one minute, keyed and
 * counted and nothing else. It is never written to KV, never logged, and never
 * put in a response.
 */
const WINDOW_MS = 60_000;
const MAX_PER_WINDOW = 5;
const MAX_TRACKED_IPS = 10_000;
const hits = new Map<string, number[]>();

function overRateLimit(ip: string, now: number): boolean {
  const recent = (hits.get(ip) ?? []).filter((t) => now - t < WINDOW_MS);

  if (recent.length >= MAX_PER_WINDOW) {
    hits.set(ip, recent);
    return true;
  }

  recent.push(now);
  hits.set(ip, recent);

  /*
   * Bound the map so a wide spread of addresses cannot grow it without limit.
   * Dropping the oldest-inserted keys is safe: losing a counter only forgives
   * a client, it never penalises one.
   */
  if (hits.size > MAX_TRACKED_IPS) {
    for (const key of hits.keys()) {
      hits.delete(key);
      if (hits.size <= MAX_TRACKED_IPS) break;
    }
  }

  return false;
}

/*
 * Security headers for responses the WORKER generates.
 *
 * `public/_headers` covers the static pages, but Cloudflare's documentation for
 * Workers static assets is explicit that those rules "are not applied to
 * responses generated by your Worker code". /api/waitlist is generated here, so
 * `_headers` never touches it: every page was covered and the single route that
 * accepts user input was not. That is the wrong way round.
 *
 * `default-src 'none'` rather than the pages' policy: this endpoint returns
 * JSON, never a document, so nothing legitimate should ever load from it.
 */
const SECURITY_HEADERS: Record<string, string> = {
  'content-type': 'application/json; charset=utf-8',
  'x-content-type-options': 'nosniff',
  'x-frame-options': 'DENY',
  'referrer-policy': 'no-referrer',
  'content-security-policy': "default-src 'none'; frame-ancestors 'none'; base-uri 'none'",
  'strict-transport-security': 'max-age=31536000; includeSubDomains',
  // An API answer is per-request and must never be cached by a proxy.
  'cache-control': 'no-store',
};

/**
 * The single place a JSON response is built, so a header can never be set on
 * one path and forgotten on another. `extra` is merged last so a caller can add
 * something like `retry-after` without restating the rest.
 */
const json = (body: unknown, status: number, extra?: Record<string, string>): Response =>
  new Response(JSON.stringify(body), {
    status,
    headers: { ...SECURITY_HEADERS, ...extra },
  });

/** Outcomes a no-JavaScript visitor can be told about, in the URL. */
type FormOutcome = 'ok' | 'already' | 'invalid' | 'slow-down' | 'error';

/**
 * Sends a form-posting browser back to the waitlist with the result in the
 * query string.
 *
 * The destination is built from THIS worker's own origin and a fixed path —
 * never from the Referer, never from a form field. A redirect target taken
 * from the request is how an endpoint becomes an open redirect, and a signup
 * form is a perfectly good place to put one by accident.
 *
 * 303 rather than 302: it forces the follow-up to be a GET, so a refresh
 * cannot resubmit the address.
 */
function redirectBack(request: Request, outcome: FormOutcome): Response {
  const target = new URL('/', request.url);
  target.search = `joined=${outcome}`;
  target.hash = 'cta';
  /*
   * Built through `json()` so there is still exactly ONE place in this file
   * that constructs a Response and therefore exactly one place that can forget
   * a security header — the rule `verify-headers.mjs` enforces. A browser
   * following a 303 ignores the body, so the JSON payload costs nothing and
   * keeps a curl user informed.
   */
  return json({ ok: outcome === 'ok' || outcome === 'already', outcome }, 303, {
    location: target.toString(),
  });
}

async function handleWaitlist(request: Request, env: Env): Promise<Response> {
  if (request.method !== 'POST') {
    return json({ ok: false, error: 'Method not allowed — use POST.' }, 405);
  }

  /*
   * Checked before the body is even read, so an abusive client costs us as
   * little as possible. CF-Connecting-IP is set by Cloudflare itself and
   * cannot be spoofed by the client; the fallback only applies off-platform
   * (wrangler dev), where one shared bucket is fine.
   */
  const ip = request.headers.get('CF-Connecting-IP') ?? 'local';
  if (overRateLimit(ip, Date.now())) {
    if ((request.headers.get('content-type') ?? '').includes('application/x-www-form-urlencoded')) {
      return redirectBack(request, 'slow-down');
    }
    return json({ ok: false, error: 'Too many attempts — please wait a minute.' }, 429, {
      'retry-after': String(WINDOW_MS / 1000),
    });
  }

  /*
   * Two callers, one endpoint.
   *
   * The hydrated page sends JSON and reads the JSON back. A BROWSER WITH NO
   * WORKING JAVASCRIPT sends `application/x-www-form-urlencoded`, because the
   * form now carries a real `action` and `method` — and it cannot read JSON,
   * so it gets a redirect it can actually follow.
   *
   * This is not hypothetical resilience. The live site's CSP blocked Next's
   * inline bootstrap scripts, React never hydrated, and the form had no
   * action, no method and no field name: every address anyone typed was
   * discarded in silence. A signup path that depends on hydration is a signup
   * path with a single point of failure, so this one no longer does.
   */
  const contentType = request.headers.get('content-type') ?? '';
  const isFormPost = contentType.includes('application/x-www-form-urlencoded');

  let email = '';
  if (isFormPost) {
    try {
      const form = await request.formData();
      const value = form.get('email');
      email = typeof value === 'string' ? value.trim() : '';
    } catch {
      return redirectBack(request, 'invalid');
    }
  } else {
    let body: { email?: unknown };
    try {
      body = (await request.json()) as { email?: unknown };
    } catch {
      return json({ ok: false, error: 'Invalid request body.' }, 400);
    }
    email = typeof body.email === 'string' ? body.email.trim() : '';
  }

  // Re-validated here even though the form validates too: the browser check is
  // a courtesy to the visitor, not a control. Anything can post to this path.
  if (!EMAIL_RE.test(email)) {
    return isFormPost
      ? redirectBack(request, 'invalid')
      : json({ ok: false, error: 'Please enter a valid email address.' }, 422);
  }

  try {
    const result = await new KvWaitlistStore(env.WAITLIST).add({
      email,
      source: 'web',
      createdAt: new Date().toISOString(),
    });
    if (isFormPost) return redirectBack(request, result.status === 'duplicate' ? 'already' : 'ok');
    return json(
      {
        ok: true,
        status: result.status,
        message:
          result.status === 'duplicate' ? "You're already on the list." : "You're on the list.",
      },
      200,
    );
  } catch {
    // The address is deliberately absent from this response and from any log
    // line: a failed write must not turn into a PII leak.
    if (isFormPost) return redirectBack(request, 'error');
    return json({ ok: false, error: 'Could not save right now — please try again.' }, 502);
  }
}

/*
 * ---------------------------------------------------------------------------
 * Nonce-based CSP for HTML
 * ---------------------------------------------------------------------------
 *
 * WHY. `script-src 'self'` blocked Next's inline bootstrap scripts
 * (`self.__next_f.push(...)`), so React never hydrated on the live site —
 * measured 25 November 2026 as `reactFiberAttached: false`. Nothing
 * interactive worked, and the waitlist form lost every address typed into it.
 *
 * WHY NOT HASHES, which would have kept HTML cacheable. Measured on the real
 * build: 99 unique executable inline scripts across 27 pages, only 3 common
 * to all of them, because each page's flight payload embeds that page's own
 * content. One global policy listing all 99 is ~7.2KB AND authorises every
 * page's scripts on every other page — a weakening dressed as strictness.
 * Per-path rules are ~535 bytes each and would keep caching, but they depend
 * on `_headers` semantics for a repeated header name: if both `/*` and the
 * page set a CSP the browser enforces the intersection and the site breaks
 * again, and any page without a rule silently gets no CSP at all. Two silent
 * failure modes on the header whose last silent failure cost every signup.
 *
 * WHY NOT 'unsafe-inline'. It would authorise any injected inline script.
 *
 * So: a fresh nonce per response, granted ONLY to inline scripts that are
 * already in the document when it leaves here. Nothing user-controlled
 * reaches this HTML — it is a static export — but the grant is still kept to
 * the narrowest set that works, rather than to every <script> on the page.
 */

/** 128 bits from the platform CSPRNG, base64 — fresh for every response. */
function makeNonce(): string {
  const bytes = crypto.getRandomValues(new Uint8Array(16));
  let binary = '';
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary);
}

/** Scripts the browser will actually execute. Anything else needs no grant. */
const EXECUTABLE_TYPES = new Set(['', 'text/javascript', 'module', 'application/javascript']);

/**
 * Serves an asset, adding a per-response nonce when it is HTML.
 *
 * Only the CSP's `script-src` is touched; every other directive, and every
 * other security header, is whatever `public/_headers` already set, so that
 * file stays the single place the policy is written.
 */
async function serveAsset(request: Request, env: Env): Promise<Response> {
  const asset = await env.ASSETS.fetch(request);
  const type = asset.headers.get('content-type') ?? '';
  if (!type.includes('text/html')) return asset;

  const nonce = makeNonce();
  const headers = new Headers(asset.headers);

  const csp = headers.get('content-security-policy');
  if (csp) {
    headers.set(
      'content-security-policy',
      csp.replace(
        /script-src ([^;]*)/i,
        (_m, sources: string) => `script-src ${sources.trim()} 'nonce-${nonce}'`,
      ),
    );
  }

  /*
   * A nonce that is reused is not a nonce. HTML must therefore not be stored
   * by a shared cache or replayed from the browser's. Static JS, CSS, fonts
   * and images are untouched above and keep their caching — they are the
   * bytes that actually benefit from it.
   */
  headers.set('cache-control', 'no-store');

  const rewritten = new HTMLRewriter()
    .on('script', {
      element(element) {
        // An external script is already covered by 'self'; granting it a
        // nonce would widen the grant for nothing.
        if (element.getAttribute('src') !== null) return;
        const scriptType = (element.getAttribute('type') ?? '').toLowerCase();
        if (!EXECUTABLE_TYPES.has(scriptType)) return;
        element.setAttribute('nonce', nonce);
      },
    })
    .transform(asset);

  return new Response(rewritten.body, { status: asset.status, headers });
}

export default {
  async fetch(request: Request, env: Env): Promise<Response> {
    const { pathname } = new URL(request.url);

    if (pathname === '/api/waitlist') return handleWaitlist(request, env);

    /*
     * THE CATALOGUE, BEFORE THE ASSET SERVICE.
     *
     * These routes are rendered from D1 on every request, which is the whole
     * point: a newly published product or a changed price appears without a
     * rebuild and without a deploy. `run_worker_first` already sends every
     * document here, so the only thing needed was somewhere to put them.
     *
     * Both helpers return null when the path is not theirs, so an unknown
     * path still falls through to the exported site exactly as before.
     */
    const api = await handleCatalogApi(request, env);
    if (api !== null) return api;

    const catalogPage = await handleCatalogPage(request, env, makeNonce());
    if (catalogPage !== null) return catalogPage;

    return serveAsset(request, env);
  },
};
